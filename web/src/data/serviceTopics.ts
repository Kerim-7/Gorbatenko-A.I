import { routes } from './content'
import type { SeoBlock } from './seoArticles'

export type ServiceTopicParent = 'upperLimb' | 'knee'

export type ServiceTopic = {
  slug: string
  parent: ServiceTopicParent
  title: string
  subtitle?: string
  lead: string
  description: string
  /** Совпадает с пунктом в upperLimbIndications / kneeIndications */
  indication: string
  blocks: SeoBlock[]
}

export function serviceTopicPath(topic: Pick<ServiceTopic, 'parent' | 'slug'>): string {
  const base = topic.parent === 'knee' ? routes.knee : routes.upperLimb
  return `${base}/${topic.slug}`
}

export function getServiceTopic(slug: string | undefined): ServiceTopic | undefined {
  if (!slug) return undefined
  return serviceTopics.find((topic) => topic.slug === slug)
}

export function topicsForParent(parent: ServiceTopicParent): ServiceTopic[] {
  return serviceTopics.filter((topic) => topic.parent === parent)
}

export function topicHrefByIndication(indication: string): string | undefined {
  const topic = serviceTopics.find((item) => item.indication === indication)
  return topic ? serviceTopicPath(topic) : undefined
}

